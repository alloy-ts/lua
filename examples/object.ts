import { Lua } from "../src/main.ts";

/**
 * Example: Defining Lua Objects (Tables) from TypeScript/JavaScript Objects using NAPI
 *
 * Questions addressed:
 * Can we define a Lua object from TS using NAPI?
 * - Yes! `lua.setGlobal(name, jsObject)` automatically converts TypeScript/JavaScript objects and arrays into native Lua tables via NAPI.
 * - Keyed TS objects (`{ key: value }`) are converted to hash tables (keyed Lua tables).
 * - Array TS objects (`[val1, val2]`) are converted to 1-indexed sequential tables (Lua arrays).
 * - Nested TS objects and arrays convert recursively into nested Lua tables.
 */

interface UserProfile {
  id: number;
  username: string;
  roles: string[];
  settings: {
    theme: string;
    notifications: boolean;
  };
}

function runObjectExample() {
  const lua = Lua.core();

  console.log("=== 1. Defining a Keyed Lua Object (Table) from a TS Object ===");

  const player = {
    name: "Hero",
    hp: 100,
    mp: 50,
    isAlive: true,
  };

  // Pass TS object into Lua global variable table via NAPI
  lua.setGlobal("player", player);

  // Read properties of the object directly from Lua
  const nameFromLua = lua.eval("return player.name");
  const hpFromLua = lua.eval("return player.hp");
  console.log("Accessing player properties in Lua -> Name:", nameFromLua, "| HP:", hpFromLua);

  // Modify object fields in Lua
  lua.eval("player.hp = player.hp - 20");
  lua.eval("player.level = 2"); // Add new property dynamically

  // Retrieve the modified object back into TS
  const updatedPlayer = lua.getGlobal("player") as Record<string, unknown>;
  console.log("Updated player object returned to TS:", updatedPlayer);

  console.log("\n=== 2. Defining a Lua Array Table from a TS Array ===");

  const items = ["Sword", "Shield", "Health Potion"];
  lua.setGlobal("inventory", items);

  // In Lua, arrays/tables are 1-indexed
  const firstItem = lua.eval("return inventory[1]"); // "Sword"
  const arrayLength = lua.eval("return #inventory"); // 3
  console.log("Lua 1-based indexing -> item[1]:", firstItem, "| Table length (#inventory):", arrayLength);

  // Append an item in Lua using table operations or indexing
  lua.eval("table.insert(inventory, 'Magic Scroll')");

  // Retrieve array back into TS (NAPI converts sequential Lua tables back to JS Arrays)
  const updatedInventory = lua.getGlobal("inventory") as string[];
  console.log("Updated inventory array in TS:", updatedInventory);

  console.log("\n=== 3. Nested TypeScript Objects and Arrays ===");

  const userProfile: UserProfile = {
    id: 1001,
    username: "alex_dev",
    roles: ["admin", "developer"],
    settings: {
      theme: "dark",
      notifications: true,
    },
  };

  lua.setGlobal("user", userProfile);

  // Access nested object properties in Lua
  const theme = lua.eval("return user.settings.theme");
  const firstRole = lua.eval("return user.roles[1]");
  console.log("Nested lookup in Lua -> user.settings.theme:", theme, "| user.roles[1]:", firstRole);

  // Perform processing in Lua on the nested table
  const formattedSummary = lua.eval(`
    return user.username .. ' (' .. user.roles[1] .. ') prefers ' .. user.settings.theme .. ' mode.'
  `);
  console.log("Formatted summary generated by Lua:", formattedSummary);

  // Read complete nested table back in TS
  const retrievedUser = lua.getGlobal("user");
  console.log("Retrieved nested user object back in TS:", JSON.stringify(retrievedUser, null, 2));
}

runObjectExample();
